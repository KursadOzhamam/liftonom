          id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
          section text NOT NULL DEFAULT 'feature',
          title text NOT NULL DEFAULT '',
          description text,
          icon text,
          sort_order int NOT NULL DEFAULT 0,
          is_active boolean NOT NULL DEFAULT true,
